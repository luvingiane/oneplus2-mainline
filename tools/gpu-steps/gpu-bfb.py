#!/usr/bin/env python3
"""gpu-bfb: write the GPU SMMU BFB settings (OnePlus msm8994-iommu.dtsi,
kgsl_iommu qcom,iommu-bfb-regs/-data; "always programmed by HLOS",
msm_iommu_sec.c) at 0xfdb10000 + reg. GPU SMMU must be powered."""
import mmap, os, struct
BFB = [(0x2000, 0x3), (0x204c, 0x3), (0x2060, 0x1555), (0x2514, 0x0), (0x2540, 0x0),
       (0x256c, 0x10), (0x20ac, 0x0), (0x215c, 0x120), (0x220c, 0x120), (0x22bc, 0x10),
       (0x2314, 0x0), (0x2394, 0x0), (0x2414, 0x0), (0x2494, 0x1), (0x2008, 0x0),
       (0x2600, 0x7), (0x2604, 0x0), (0x2608, 0x20), (0x260c, 0x20), (0x2610, 0xc),
       (0x2614, 0x0), (0x2618, 0x0), (0x261c, 0x0), (0x2620, 0x10), (0x2624, 0x0),
       (0x2628, 0x0), (0x262c, 0x10)]
f = os.open("/dev/mem", os.O_RDWR | os.O_SYNC)
m = mmap.mmap(f, 0x1000, mmap.MAP_SHARED, mmap.PROT_READ | mmap.PROT_WRITE, offset=0xfdb12000)
for reg, val in BFB:
    o = reg - 0x2000
    old = struct.unpack("<I", m[o:o + 4])[0]
    m[o:o + 4] = struct.pack("<I", val)
    print(f"{0xfdb10000 + reg:#x}: {old:#x} -> {struct.unpack('<I', m[o:o + 4])[0]:#x}")
